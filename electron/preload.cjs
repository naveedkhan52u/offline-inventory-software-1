const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('inventoryAPI', {
  authStatus: () => ipcRenderer.invoke('auth:status'),
  createAccount: (data) => ipcRenderer.invoke('auth:create', data),
  login: (data) => ipcRenderer.invoke('auth:login', data),
  getBusinessSettings: () => ipcRenderer.invoke('settings:get-business'),
  saveBusinessSettings: (data) => ipcRenderer.invoke('settings:save-business', data),
  getDashboardSummary: () => ipcRenderer.invoke('dashboard:summary'),
  getAnalyticsOverview: (options) => ipcRenderer.invoke('analytics:overview', options),
  generateReports: (filters) => ipcRenderer.invoke('reports:generate', filters),
  listStaff: (filters) => ipcRenderer.invoke('staff:list', filters),
  saveStaff: (data) => ipcRenderer.invoke('staff:save', data),
  createStaffPayment: (data) => ipcRenderer.invoke('staff:payment:create', data),
  listExpenses: (filters) => ipcRenderer.invoke('expenses:list', filters),
  createExpense: (data) => ipcRenderer.invoke('expenses:create', data),
  deleteExpense: (id) => ipcRenderer.invoke('expenses:delete', id),
  getProfitLossSummary: (filters) => ipcRenderer.invoke('profit-loss:summary', filters),
  listSales: (filters) => ipcRenderer.invoke('sales:list', filters),
  createSale: (data) => ipcRenderer.invoke('sales:create', data),
  printBill: (data) => ipcRenderer.invoke('billing:print', data),
  listPurchases: (filters) => ipcRenderer.invoke('purchases:list', filters),
  createPurchase: (data) => ipcRenderer.invoke('purchases:create', data),
  listStockMovements: (filters) => ipcRenderer.invoke('stock:movements', filters),
  adjustStock: (data) => ipcRenderer.invoke('stock:adjust', data),
  listProducts: () => ipcRenderer.invoke('products:list'),
  createProduct: (data) => ipcRenderer.invoke('products:create', data),
  updateProduct: (id, data) => ipcRenderer.invoke('products:update', id, data),
  deleteProduct: (id) => ipcRenderer.invoke('products:delete', id)
});
